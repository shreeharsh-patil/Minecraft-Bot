"""Generate native item defaults from Mojang's 1.21.4 --reports output.

This is a development tool only. It never starts a server or accepts the EULA.
Run the jar with -DbundlerMainClass=net.minecraft.data.Main --reports first.
"""
import argparse
import hashlib
import json
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("reports", type=Path)
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
items_bytes = (args.reports / "items.json").read_bytes()
items = json.loads(items_bytes)
registries_bytes = (args.reports / "registries.json").read_bytes()
entries = json.loads(registries_bytes)["minecraft:item"]["entries"]
ordered = sorted(entries, key=lambda name: entries[name]["protocol_id"])
assert [entries[name]["protocol_id"] for name in ordered] == list(range(len(ordered)))
assert set(ordered) == set(items), "Registry and component report disagree"
values = []
for name in ordered:
    components = items[name]["components"]
    size = components["minecraft:max_stack_size"]
    damage = components.get("minecraft:max_damage", 0)
    assert 1 <= size <= 99 and 0 <= damage <= 65535
    values.append([name, size, damage])
data = root / "native" / "data"
data.mkdir(exist_ok=True)
(data / "items-1.21.4.json").write_text(json.dumps(values, indent=2) + "\n", encoding="utf-8")
header = (
    "// Generated by scripts/generate-item-properties.py from Mojang 1.21.4 reports.\n"
    "// Do not hand-edit. Protocol IDs are checked against the pinned registry in tests.\n"
    f"// items.json SHA-256: {hashlib.sha256(items_bytes).hexdigest()}\n"
    f"// registries.json SHA-256: {hashlib.sha256(registries_bytes).hexdigest()}\n"
    "use super::Properties;\n"
    f"pub const ITEM_PROPERTIES: [Properties; {len(values)}] = [\n"
)
body = "".join(f"    Properties::new({size}, {damage}), // {name}\n" for name, size, damage in values)
(root / "native" / "src" / "item_defaults.rs").write_text(header + body + "];\n", encoding="utf-8")
print(f"Generated defaults for {len(values)} items.")
